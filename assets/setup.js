// setup.js
// Logic for setup.html: tests a GitHub token against the vault repo,
// encrypts it with the chosen password and prints a ready config.js.
// Runs only in the browser; the token is sent to api.github.com and nowhere else.

import { encryptToken } from "./crypto.js";
import { Vault } from "./github.js";

const $ = (id) => document.getElementById(id);

// On https://<user>.github.io/... the username is already known
const pagesUser = location.hostname.match(/^([a-z0-9-]+)\.github\.io$/i)?.[1];
if (pagesUser) $("owner").value = pagesUser;

$("form").addEventListener("submit", async (e) => {
  e.preventDefault();
  $("err").textContent = "";
  const owner = $("owner").value.trim();
  const repo = $("repo").value.trim();
  const token = $("token").value.trim();
  const pw = $("pw").value;
  if (pw !== $("pw2").value) return ($("err").textContent = "Passwords don't match.");
  if (pw.length < 10 || /^(.)\1+$/.test(pw) || /^(password|passwort|1234567890|qwertzuiop|qwertyuiop)/i.test(pw)) {
    return ($("err").textContent = "Choose a stronger password: at least 10 characters, not a common word or pattern.");
  }

  const btn = $("go");
  btn.disabled = true;
  btn.innerHTML = '<span class="spinner"></span> Testing token';
  try {
    const vault = new Vault({ owner, repo, folder: "files", token });
    await vault.check();
    if (vault.isPrivate === false) {
      throw new Error(`${owner}/${repo} is public. The vault must be a private repo, or anyone could read your documents.`);
    }
    btn.innerHTML = '<span class="spinner"></span> Encrypting';
    const blob = await encryptToken(token, pw);
    $("out").value = configFile(owner, repo, blob);
    $("result").hidden = false;
    $("result").scrollIntoView({ behavior: "smooth" });
  } catch (err) {
    $("err").textContent =
      err.status === 401 ? "Token is not valid." :
      err.status === 404 ? `Can't see ${owner}/${repo}. Check the name and that the token has access to this repo.` :
      err.message || "Something went wrong.";
  } finally {
    btn.disabled = false;
    btn.textContent = "Test token and generate config";
  }
});

$("copy").addEventListener("click", async () => {
  try {
    await navigator.clipboard.writeText($("out").value);
  } catch {
    $("out").select();
    document.execCommand("copy");
  }
  $("copy").textContent = "Copied";
});

function configFile(owner, repo, blob) {
  return `// a really helpful tool: configuration. Generated by setup.html on ${new Date().toISOString().slice(0, 10)}.
// Safe to be public: the token below is AES-256 encrypted with your password.
// To change password or token, run setup.html again. See docs/SETUP.md.

export default {
  owner: ${JSON.stringify(owner)},
  repo: ${JSON.stringify(repo)},
  folder: "files",
  maxFileMB: 25,
  encryptedToken: ${JSON.stringify(blob, null, 4).replace(/\n}/, "\n  }")},
};
`;
}
